#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the capacity-matched baseline and adaptive stopping tables."""

from __future__ import annotations

import csv
import argparse
import math
import statistics as st
from pathlib import Path


RUNS_ROOT = Path("runs")


def adaptive_rows(root):
    combined = root / "phase2_adaptive/tables/adaptive_all.csv"
    paths = [combined] if combined.exists() else [
        root / name / "tables/adaptive.csv"
        for name in ("phase2_adaptive", "phase2_adaptive_b")
    ]
    rows = []
    for path in paths:
        if path.exists():
            with path.open(newline="", encoding="utf-8") as stream:
                rows.extend(csv.DictReader(stream))
    if not rows:
        raise FileNotFoundError(f"No adaptive results under {root}")
    keys = [(r["d"], r["seed"], r["tau"]) for r in rows]
    if len(keys) != len(set(keys)):
        raise ValueError("Duplicate adaptive dimension/seed/tolerance rows")
    return rows


def load(p):
    path = Path(p)
    if path.parts[0] == "runs":
        path = RUNS_ROOT / path.relative_to("runs")
    if not path.exists() and path.name == "adaptive_all.csv":
        return adaptive_rows(RUNS_ROOT)
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def sci(m, s=None):
    e = int(math.floor(math.log10(abs(m))))
    mant = m / 10**e
    if s is None:
        return rf"${mant:.2f}{{\times}}10^{{{e}}}$"
    digits = round(s / 10**e * 100)
    return rf"${mant:.2f}({digits}){{\times}}10^{{{e}}}$"


def agg(rows, method, K=None):
    v = [r for r in rows if r["method"] == method and (K is None or r["K"] == str(K))]
    E = [float(r["Energy_RMS"]) for r in v]
    R = [float(r["Residual_RMS"]) for r in v]
    t = [float(r["cum_train_seconds"]) for r in v]
    return (st.mean(E), st.stdev(E) if len(E) > 1 else None,
            st.mean(R), st.mean(t))


def main():
    global RUNS_ROOT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs-root", type=Path, default=Path("runs"))
    parser.add_argument("--tab-dir", type=Path, default=Path("tables"))
    args = parser.parse_args()
    RUNS_ROOT = args.runs_root
    tab = args.tab_dir
    tab.mkdir(parents=True, exist_ok=True)

    # ---------------- baselines (Experiment C) ----------------
    lines = [
        "% Auto-generated by make_phase123_tables.py -- do not edit by hand.",
        r"\begin{tabular}{llcccc}", r"\toprule",
        r"$n$ & method & params & $E$ & $\|\mathcal R\|$ & wall (s) \\",
    ]
    for d, hi_dir, p1_dir in (
        (50, "runs/sweep2_ring_high", "runs/phase1_ring50"),
        (100, "runs/sweep2_ring_high", "runs/phase1_ring100"),
    ):
        hi = [r for r in load(f"{hi_dir}/tables/metrics.csv") if r["d"] == str(d)]
        p1 = load(f"{p1_dir}/tables/metrics.csv")
        e8 = [r for r in load("runs/sweep2_ring50_e8k/tables/metrics.csv")
              if r["d"] == str(d)] if d == 50 else \
             [r for r in load("runs/sweep2_ring100_K8_e8k/tables/metrics.csv")
              if r["d"] == str(d)]
        lines.append(r"\midrule")
        rows = [
            ("Newton--PINN ($K{=}4$)", "$4N_{\\rm par}$") + agg(hi, "Newton-PINN", 4),
            ("Newton--PINN ($K{=}4$, $8000$\\,ep)", "$4N_{\\rm par}$") + agg(e8, "Newton-PINN", 4),
            ("Seq.\\ nonlinear (C3, $K{=}4$)", "$4N_{\\rm par}$") + agg(p1, "Seq-Nonlinear", 4),
            ("Composite direct (C2)", "$4N_{\\rm par}$") + agg(p1, "Composite-Direct"),
            ("Direct, single net (C1)", "$N_{\\rm par}$") + agg(hi, "Direct-PINN"),
        ]
        for name, par, Em, Es, Rm, tm in rows:
            lines.append(
                f"{d} & {name} & {par} & {sci(Em, Es)} & {sci(Rm)} & {tm:.0f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (tab / "baselines_table.tex").write_text("\n".join(lines), encoding="utf-8")
    (tab / "baselines_table_edited.tex").write_text("\n".join(lines), encoding="utf-8")
    print(f"[saved] {tab / 'baselines_table.tex'}")

    # ---------------- adaptive stopping (Experiment B) ----------------
    allr = load("runs/phase2_adaptive/tables/adaptive_all.csv")
    lines = [
        "% Auto-generated by make_phase123_tables.py -- do not edit by hand.",
        r"\begin{tabular}{llcccccc}", r"\toprule",
        r"$n$ & $\tau$ & stop reason & $K$ & epochs & $E$ & $\mathfrak C$ "
        r"& $E\le\tau$ \\",
    ]
    for d in ("10", "20", "50"):
        lines.append(r"\midrule")
        for tau in ("0.3", "0.1", "0.05"):
            rs = [r for r in allr if r["d"] == d and r["tau"] == tau]
            if not rs:
                continue
            reasons = sorted({r["stop_reason"] for r in rs})
            display_reason = {
                "certified": "indicator",
                "floor_certificate": "indicator_floor",
            }
            reason = "/".join(
                display_reason.get(r, r).replace("_", "\\_") for r in reasons
            )
            Ks = sorted(int(r["K"]) for r in rs)
            eps = sorted(int(r["epochs_used"]) for r in rs)
            E = [float(r["Energy_RMS"]) for r in rs]
            C = [float(r["Certificate_RMS"]) for r in rs]
            ok = sum(1 for r in rs if float(r["Energy_RMS"]) <= float(r["tau"]))
            k_str = f"{Ks[0]}" if Ks[0] == Ks[-1] else f"{Ks[0]}--{Ks[-1]}"
            ep_str = (f"{eps[0]}" if eps[0] == eps[-1]
                      else f"{eps[0]}--{eps[-1]}")
            lines.append(
                f"{d} & {tau} & {reason} & {k_str} & {ep_str} "
                f"& {sci(st.mean(E), st.stdev(E) if len(E) > 1 else None)} "
                f"& {sci(st.mean(C), st.stdev(C) if len(C) > 1 else None)} "
                f"& {ok}/{len(rs)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (tab / "adaptive_table.tex").write_text("\n".join(lines), encoding="utf-8")
    print(f"[saved] {tab / 'adaptive_table.tex'}")


if __name__ == "__main__":
    main()
